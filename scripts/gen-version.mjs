// Writes www/js/version.js with the version, build number, commit, build date and the full CHANGELOG,
// so the app can show "About" details and an in-app "What's new". Run before `cap sync`.
import fs from 'node:fs';
import { execSync } from 'node:child_process';

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
let commit = process.env.GITHUB_SHA || '';
if (!commit) { try { commit = execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* not a git checkout */ } }

const info = {
  version: pkg.version,
  build: Number(process.env.VERSION_CODE || process.env.GITHUB_RUN_NUMBER) || null,
  commit: commit.slice(0, 7),
  date: new Date().toISOString(),
  changelog: fs.readFileSync('CHANGELOG.md', 'utf8'),
};
fs.writeFileSync('www/js/version.js', `/* Generated by scripts/gen-version.mjs. Do not edit. */\nwindow.TB_BUILD = ${JSON.stringify(info)};\n`);
console.log(`version.js → v${info.version} build ${info.build ?? 'dev'} ${info.commit}`);
